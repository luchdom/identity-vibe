using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Architecture.UnitTests;

internal sealed record BackendSourceFile(
    string AssemblyName,
    string RelativePath,
    IReadOnlyList<BaseTypeDeclarationSyntax> Types)
{
    public static IEnumerable<BackendSourceFile> ReadAll(string repositoryRoot)
    {
        var assemblyName = string.Empty;
        var parseOptions = CSharpParseOptions.Default;

        foreach (var entry in File.ReadLines(Path.Combine(AppContext.BaseDirectory, "BackendCompilerInputs.txt")))
        {
            if (entry.StartsWith("Project|", StringComparison.Ordinal))
            {
                var project = entry.Split('|', 4);
                assemblyName = project[1];
                if (!LanguageVersionFacts.TryParse(project[2], out var languageVersion))
                {
                    throw new InvalidDataException($"Unexpected C# language version '{project[2]}' for {assemblyName}.");
                }

                parseOptions = new CSharpParseOptions(
                    languageVersion,
                    preprocessorSymbols: project[3].Split([';', ','],
                        StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries));
                continue;
            }

            if (string.IsNullOrEmpty(assemblyName) || !entry.StartsWith("Source|", StringComparison.Ordinal))
            {
                throw new InvalidDataException($"Unexpected backend compiler input: {entry}");
            }

            var sourcePath = entry["Source|".Length..];
            var repositoryPath = Path.GetRelativePath(repositoryRoot, sourcePath);
            var root = CSharpSyntaxTree.ParseText(File.ReadAllText(sourcePath), parseOptions, repositoryPath)
                .GetCompilationUnitRoot();
            var generated = root.GetLeadingTrivia().Any(trivia =>
                (trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
                && trivia.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));

            if (!generated)
            {
                yield return new BackendSourceFile(assemblyName, repositoryPath,
                    root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>().ToArray());
            }
        }
    }

    public static bool IsTopLevel(BaseTypeDeclarationSyntax type) =>
        type.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax;

    public static bool IsRecordClass(BaseTypeDeclarationSyntax type) =>
        type is RecordDeclarationSyntax record && !record.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword);

    public static string GetMetadataName(BaseTypeDeclarationSyntax type)
    {
        var namespaces = type.Ancestors().OfType<BaseNamespaceDeclarationSyntax>().Reverse()
            .Select(ns => string.Concat(ns.Name.DescendantTokens().Select(token => token.ValueText)));
        var types = type.AncestorsAndSelf().OfType<BaseTypeDeclarationSyntax>().Reverse()
            .Select(declaration => declaration is TypeDeclarationSyntax { Arity: > 0 } generic
                ? $"{declaration.Identifier.ValueText}`{generic.Arity}"
                : declaration.Identifier.ValueText);

        return string.Join('.', namespaces.Append(string.Join('+', types)));
    }
}
